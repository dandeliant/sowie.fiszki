-- 5. RPC publiczne (formularz bez logowania) --------------------------------

-- Ustawienia + aktywne pytania. Formularz zamknięty → form_open=false, bez pytań.
create or replace function public.sowizwiad_get_form()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c public.sowizwiad_config; v_q jsonb;
begin
  select * into c from public.sowizwiad_config where id = 1;
  if not found then
    return jsonb_build_object('ok', true, 'form_open', false, 'title', 'SowiZwiad', 'intro', '', 'questions', '[]'::jsonb);
  end if;
  if not c.form_open then
    return jsonb_build_object('ok', true, 'form_open', false, 'title', c.title, 'intro', c.intro, 'questions', '[]'::jsonb);
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('id', q.id, 'section', q.section, 'text', q.text)
                            order by q.position, q.id), '[]'::jsonb)
    into v_q
    from public.sowizwiad_questions q
   where q.active;
  return jsonb_build_object('ok', true, 'form_open', true, 'title', c.title, 'intro', c.intro, 'questions', v_q);
end; $$;

-- Wysłanie odpowiedzi. p_answers = obiekt {"<id pytania>": "odpowiedź", …}.
-- Zapisywane są tylko AKTYWNE pytania (kopia treści), inne klucze są pomijane.
-- Zwraca {ok:true, id, answered, total[, duplicate:true]} albo {ok:false, error}.
create or replace function public.sowizwiad_submit(p_name text, p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_open     boolean;
  v_name     text;
  v_snap     jsonb := '[]'::jsonb;
  v_answered int := 0;
  v_total    int := 0;
  v_chars    int := 0;
  v_a        text;
  v_id       uuid;
  q          record;
begin
  select form_open into v_open from public.sowizwiad_config where id = 1;
  if coalesce(v_open, true) = false then
    return jsonb_build_object('ok', false, 'error', 'Formularz jest chwilowo zamknięty.');
  end if;

  -- imię: bez znaków sterujących, pojedyncze spacje, 1–100 znaków
  v_name := regexp_replace(coalesce(p_name, ''), '[[:cntrl:]]', ' ', 'g');
  v_name := btrim(regexp_replace(v_name, '\s+', ' ', 'g'));
  if v_name = '' then
    return jsonb_build_object('ok', false, 'error', 'Podaj swoje imię.');
  end if;
  if char_length(v_name) > 100 then
    return jsonb_build_object('ok', false, 'error', 'Imię jest za długie (maks. 100 znaków).');
  end if;

  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    return jsonb_build_object('ok', false, 'error', 'Nieprawidłowe dane formularza.');
  end if;
  if octet_length(p_answers::text) > 600000
     or (select count(*) from jsonb_object_keys(p_answers)) > 1000 then
    return jsonb_build_object('ok', false, 'error', 'Odpowiedzi są za długie.');
  end if;
  if exists (select 1 from jsonb_each(p_answers) e where jsonb_typeof(e.value) not in ('string', 'null')) then
    return jsonb_build_object('ok', false, 'error', 'Nieprawidłowe dane formularza.');
  end if;

  for q in select id, section, text from public.sowizwiad_questions where active order by position, id loop
    v_total := v_total + 1;
    v_a := coalesce(p_answers ->> (q.id::text), '');
    v_a := replace(replace(v_a, E'\r\n', E'\n'), E'\r', E'\n');
    v_a := regexp_replace(v_a, E'[\\x01-\\x08\\x0B\\x0C\\x0E-\\x1F\\x7F]', '', 'g');
    v_a := btrim(v_a, E' \t\n');
    if char_length(v_a) > 3000 then
      return jsonb_build_object('ok', false, 'error',
        format('Odpowiedź na pytanie nr %s jest za długa (maks. 3000 znaków).', v_total));
    end if;
    if v_a <> '' then
      v_answered := v_answered + 1;
      v_chars := v_chars + char_length(v_a);
    end if;
    v_snap := v_snap || jsonb_build_array(jsonb_build_object('qid', q.id, 'section', q.section, 'q', q.text, 'a', v_a));
  end loop;

  if v_answered = 0 then
    return jsonb_build_object('ok', false, 'error', 'Odpowiedz na co najmniej jedno pytanie.');
  end if;
  if v_chars > 150000 then
    return jsonb_build_object('ok', false, 'error', 'Odpowiedzi są za długie (łącznie maks. 150 000 znaków).');
  end if;

  -- jedno wysyłanie naraz: sprawdzenie duplikatu i limitu bez wyścigów
  perform pg_advisory_xact_lock(hashtext('sowizwiad_submit'));

  -- podwójne kliknięcie / ponowne wysłanie: to samo imię + te same odpowiedzi w ciągu 2 minut
  select r.id into v_id
    from public.sowizwiad_responses r
   where lower(r.name) = lower(v_name)
     and r.answers = v_snap
     and r.created_at > now() - interval '2 minutes'
   order by r.created_at desc
   limit 1;
  if v_id is not null then
    return jsonb_build_object('ok', true, 'id', v_id, 'answered', v_answered, 'total', v_total, 'duplicate', true);
  end if;

  -- globalny limit: maks. 60 zgłoszeń w ciągu 10 minut
  if (select count(*) from public.sowizwiad_responses where created_at > now() - interval '10 minutes') >= 60 then
    return jsonb_build_object('ok', false, 'error', 'Zbyt wiele zgłoszeń, spróbuj za chwilę.');
  end if;

  insert into public.sowizwiad_responses (name, answers, answered, total)
  values (v_name, v_snap, v_answered, v_total)
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id, 'answered', v_answered, 'total', v_total);
end; $$;

-- 6. RPC admina: zapis całej listy pytań ------------------------------------
-- p_questions = [{id: <id istniejącego pytania> | null (nowe), section, text, active}, …]
-- w docelowej kolejności (position = numer na liście). Pytania spoza listy są usuwane.
-- p_rev = questions_rev z chwili wczytania edytora (null = bez sprawdzania);
-- inna wartość → {ok:false, code:'CONFLICT'} (lista zmieniona w innej karcie).
create or replace function public.sowizwiad_save_questions(p_questions jsonb, p_rev int default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_rev  int;
  v_keep bigint[] := '{}';
  v_id   bigint;
  v_txt  text;
  v_sec  text;
  v_act  boolean;
  v_pos  int := 0;
  e      jsonb;
  v_list jsonb;
begin
  if not public._is_admin() then
    return jsonb_build_object('ok', false, 'error', 'Brak uprawnień administratora.');
  end if;
  if p_questions is null or jsonb_typeof(p_questions) <> 'array' then
    return jsonb_build_object('ok', false, 'error', 'Nieprawidłowa lista pytań.');
  end if;
  if jsonb_array_length(p_questions) > 500 then
    return jsonb_build_object('ok', false, 'error', 'Za dużo pytań (maks. 500).');
  end if;

  insert into public.sowizwiad_config (id) values (1) on conflict (id) do nothing;
  select questions_rev into v_rev from public.sowizwiad_config where id = 1 for update;
  if p_rev is not null and p_rev is distinct from v_rev then
    return jsonb_build_object('ok', false, 'code', 'CONFLICT',
      'error', 'Lista pytań zmieniła się w międzyczasie (np. w innej karcie). Wczytaj ją ponownie.');
  end if;

  -- walidacja całości przed jakimkolwiek zapisem
  for e in select value from jsonb_array_elements(p_questions) loop
    v_pos := v_pos + 1;
    if jsonb_typeof(e) <> 'object' then
      return jsonb_build_object('ok', false, 'error', 'Nieprawidłowa lista pytań.');
    end if;
    v_txt := btrim(regexp_replace(coalesce(e ->> 'text', ''), '[[:cntrl:]]', ' ', 'g'));
    v_sec := btrim(regexp_replace(coalesce(e ->> 'section', ''), '[[:cntrl:]]', ' ', 'g'));
    if v_txt = '' or char_length(v_txt) > 500 then
      return jsonb_build_object('ok', false, 'error', format('Pytanie nr %s: treść musi mieć 1–500 znaków.', v_pos));
    end if;
    if char_length(v_sec) > 120 then
      return jsonb_build_object('ok', false, 'error', format('Pytanie nr %s: nazwa sekcji może mieć maks. 120 znaków.', v_pos));
    end if;
    if jsonb_typeof(e -> 'id') = 'number' then
      v_id := (e ->> 'id')::bigint;
      if v_id = any (v_keep) then
        return jsonb_build_object('ok', false, 'error', 'Pytanie występuje na liście dwa razy.');
      end if;
      v_keep := v_keep || v_id;
    end if;
  end loop;

  -- usunięte z listy
  delete from public.sowizwiad_questions where not (id = any (v_keep));

  v_pos := 0;
  for e in select value from jsonb_array_elements(p_questions) loop
    v_pos := v_pos + 1;
    v_txt := btrim(regexp_replace(coalesce(e ->> 'text', ''), '[[:cntrl:]]', ' ', 'g'));
    v_sec := btrim(regexp_replace(coalesce(e ->> 'section', ''), '[[:cntrl:]]', ' ', 'g'));
    v_act := coalesce((e ->> 'active')::boolean, true);
    v_id := null;
    if jsonb_typeof(e -> 'id') = 'number' then
      update public.sowizwiad_questions
         set section = v_sec, text = v_txt, position = v_pos, active = v_act,
             updated_at = case when (section, text, active) is distinct from (v_sec, v_txt, v_act)
                               then now() else updated_at end
       where id = (e ->> 'id')::bigint
      returning id into v_id;
    end if;
    if v_id is null then
      insert into public.sowizwiad_questions (section, text, position, active)
      values (v_sec, v_txt, v_pos, v_act);
    end if;
  end loop;

  update public.sowizwiad_config set questions_rev = questions_rev + 1 where id = 1
  returning questions_rev into v_rev;

  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'section', section, 'text', text, 'position', position, 'active', active)
                            order by position, id), '[]'::jsonb)
    into v_list from public.sowizwiad_questions;
  return jsonb_build_object('ok', true, 'rev', v_rev, 'questions', v_list);
end; $$;

