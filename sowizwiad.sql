-- Strona sowizwiad.html (/sowizwiad): każdy (bez logowania) wpisuje imię
-- i odpowiedzi na pytania, wysyła je; administrator czyta odpowiedzi
-- (kopiuje jako tekst / drukuje) i edytuje listę pytań (sowizwiad.html#admin).
--
-- Tabele:
--   sowizwiad_config    — ustawienia (1 wiersz, id=1): tytuł, wstęp, formularz otwarty
--   sowizwiad_questions — pytania: sekcja, treść, kolejność, aktywne/ukryte
--   sowizwiad_responses — wysłane odpowiedzi; `answers` = KOPIA pytań z chwili
--                         wysłania [{qid, section, q, a}] (późniejsza edycja lub
--                         usunięcie pytań nie psuje starych odpowiedzi)
-- Wszystkie trzy: odczyt i zapis tylko admin (RLS _is_admin()); anon nie ma
-- żadnych uprawnień do tabel — formularz działa przez RPC SECURITY DEFINER:
--   sowizwiad_get_form()            — anon + zalogowani: ustawienia + aktywne pytania
--   sowizwiad_submit(name, answers) — anon + zalogowani: walidacja + zapis kopii
--   sowizwiad_save_questions(list, rev) — tylko admin: zapis całej listy pytań
--                                     w jednej transakcji (kolejność, sekcje, usuwanie)
--
-- Wymaga: helper public._is_admin() (migracja #20). Idempotentna.

-- 1. Ustawienia -------------------------------------------------------------
create table if not exists public.sowizwiad_config (
  id            int primary key default 1,
  title         text not null default 'SowiZwiad',
  intro         text not null default 'Odpowiedz po angielsku na pytania poniżej — krótko albo pełnymi zdaniami, jak umiesz. Możesz pominąć każde pytanie, na które nie chcesz lub nie umiesz odpowiedzieć.',
  form_open     boolean not null default true,
  questions_rev int not null default 0,          -- rośnie przy każdym zapisie listy pytań
  seeded_at     timestamptz,                     -- pytania startowe wstawione (tylko raz)
  updated_at    timestamptz not null default now(),
  constraint sowizwiad_config_singleton check (id = 1),
  constraint sowizwiad_config_title_len check (char_length(title) between 1 and 120),
  constraint sowizwiad_config_intro_len check (char_length(intro) <= 4000)
);
insert into public.sowizwiad_config (id) values (1) on conflict (id) do nothing;

-- 2. Pytania ----------------------------------------------------------------
create table if not exists public.sowizwiad_questions (
  id         bigint generated by default as identity primary key,
  section    text not null default '',
  text       text not null,
  position   int not null default 0,
  active     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sowizwiad_questions_text_len check (char_length(text) between 1 and 500),
  constraint sowizwiad_questions_section_len check (char_length(section) <= 120)
);
create index if not exists sowizwiad_questions_pos_idx on public.sowizwiad_questions (position, id);

-- 3. Odpowiedzi -------------------------------------------------------------
create table if not exists public.sowizwiad_responses (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  answers    jsonb not null default '[]'::jsonb,  -- [{qid, section, q, a}] — wszystkie aktywne pytania, a = '' gdy pominięte
  answered   int not null default 0,              -- ile niepustych odpowiedzi
  total      int not null default 0,              -- ile pytań było w formularzu
  is_read    boolean not null default false,
  created_at timestamptz not null default now(),
  constraint sowizwiad_responses_name_len check (char_length(name) between 1 and 100),
  constraint sowizwiad_responses_answers_arr check (jsonb_typeof(answers) = 'array')
);
create index if not exists sowizwiad_responses_created_idx on public.sowizwiad_responses (created_at desc);

-- 4. RLS + uprawnienia do tabel ---------------------------------------------
alter table public.sowizwiad_config    enable row level security;
alter table public.sowizwiad_questions enable row level security;
alter table public.sowizwiad_responses enable row level security;

drop policy if exists "sz_cfg_admin" on public.sowizwiad_config;
create policy "sz_cfg_admin" on public.sowizwiad_config for all to authenticated
  using (public._is_admin()) with check (public._is_admin());

drop policy if exists "sz_q_admin" on public.sowizwiad_questions;
create policy "sz_q_admin" on public.sowizwiad_questions for all to authenticated
  using (public._is_admin()) with check (public._is_admin());

-- odpowiedzi: admin czyta, oznacza przeczytane (tylko kolumna is_read), usuwa.
-- Brak polityki INSERT — nowe wiersze wyłącznie przez sowizwiad_submit.
drop policy if exists "sz_resp_select" on public.sowizwiad_responses;
create policy "sz_resp_select" on public.sowizwiad_responses for select to authenticated
  using (public._is_admin());
drop policy if exists "sz_resp_update" on public.sowizwiad_responses;
create policy "sz_resp_update" on public.sowizwiad_responses for update to authenticated
  using (public._is_admin()) with check (public._is_admin());
drop policy if exists "sz_resp_delete" on public.sowizwiad_responses;
create policy "sz_resp_delete" on public.sowizwiad_responses for delete to authenticated
  using (public._is_admin());

